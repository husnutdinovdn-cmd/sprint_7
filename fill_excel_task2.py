def write_sheet(ws):
    # Удалить все строки (избегаем MergedCell)
    mr = ws.max_row or 0
    if mr > 0:
        ws.delete_rows(1, mr)
    # Заголовки (строка 1)
    h = ['id тест-кейса', 'Название тест-кейса', 'Предусловия', 'Номер шага', 'Описание шага', 'ОР', 'Окружение']
    for col in range(1, 8):
        ws.cell(row=1, column=col, value=h[col - 1])
    row = 2
    for tc in TEST_CASES:
        id_tc, name, precond, steps, or_result, env = tc
        for i, (step_num, step_desc) in enumerate(steps):
            ws.cell(row=row, column=1, value=id_tc if i == 0 else None)
            ws.cell(row=row, column=2, value=name if i == 0 else None)
            ws.cell(row=row, column=3, value=precond if i == 0 else None)
            ws.cell(row=row, column=4, value=step_num)
            ws.cell(row=row, column=5, value=step_desc)
            ws.cell(row=row, column=6, value=or_result if i == 0 else None)
            ws.cell(row=row, column=7, value=env if i == 0 else None)
            row += 1
        row += 1  # пустая строка между кейсами


def main():
    wb = openpyxl.load_workbook(PATH)
    ws = wb[SHEET_NAME]
    write_sheet(ws)
    wb.save(PATH)
    print("OK: тест-кейсы Задание 2 записаны.")


if __name__ == "__main__":
    main()
