def update_checklist(ws):
    for row_idx, status, bug_ref in CHECKLIST_RESULTS:
        excel_row = row_idx + 2   # данные чек-листа: строка 1 = заголовок, 2+ = пункты
        if status:
            ws.cell(row=excel_row, column=3, value=status)
        if bug_ref:
            ws.cell(row=excel_row, column=4, value=bug_ref)

def update_validation(ws):
    if ws.max_column < 8:
        ws.cell(row=1, column=8, value="Ссылка на баг-репорт")
    for row_idx, status, bug_ref in VALIDATION_RESULTS:
        excel_row = row_idx + 2
        if status:
            ws.cell(row=excel_row, column=7, value=status)
        if bug_ref:
            ws.cell(row=excel_row, column=7, value=status)
            ws.cell(row=excel_row, column=8, value=bug_ref)

def update_bug_reports(ws):
    # Заголовки: ID, Название БР, Приоритет, Статус, Предусловия, Шаги воспроизведения, Ожидаемый результат, Фактический результат
    ws.cell(row=1, column=8, value="Фактический результат")
    start = 2
    for i, (bid, title, prio, status, pre, steps, expected, actual) in enumerate(BUG_REPORTS):
        row = start + i
        ws.cell(row=row, column=1, value=bid)
        ws.cell(row=row, column=2, value=title)
        ws.cell(row=row, column=3, value=prio)
        ws.cell(row=row, column=4, value=status)
        ws.cell(row=row, column=5, value=pre)
        ws.cell(row=row, column=6, value=steps)
        ws.cell(row=row, column=7, value=expected)
        ws.cell(row=row, column=8, value=actual)
    # Очистить строки, оставшиеся от удалённых багов
    for row in range(start + len(BUG_REPORTS), (ws.max_row or 0) + 1):
        for col in range(1, (ws.max_column or 8) + 1):
            ws.cell(row=row, column=col).value = None

def update_bugs_outside(ws):
    # Заголовок в 1, данные со 2. Колонки: Заголовок, Ссылка на баг-репорт.
    # Очищаем старые данные (в т.ч. по лендингу — его не проверяем по заданию).
    for row in range(2, (ws.max_row or 0) + 1):
        for col in range(1, (ws.max_column or 2) + 1):
            ws.cell(row=row, column=col).value = None
    for i, (title, ref) in enumerate(BUGS_OUTSIDE):
        ws.cell(row=2 + i, column=1, value=title)
        ws.cell(row=2 + i, column=2, value=ref)

def main():
    wb = openpyxl.load_workbook(PATH)
    update_checklist(wb["Задание 1 чек-лист"])
    update_validation(wb["Задание 1 данные валидации"])
    update_bug_reports(wb["Баг-репорты"])
    update_bugs_outside(wb["Задание 1 баги вне тестовой док"])
    wb.save(PATH)
    print("OK: результаты, баг-репорты и баги вне тестовой док обновлены.")

if __name__ == "__main__":
    main()
