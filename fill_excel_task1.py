def clear_sheet(ws, start_row=1):
    """Удалить содержимое начиная с start_row."""
    for row in range(start_row, ws.max_row + 1) if ws.max_row else []:
        for col in range(1, ws.max_column + 1) if ws.max_column else []:
            ws.cell(row=row, column=col).value = None

def write_checklist(ws):
    ws.delete_rows(1, ws.max_row or 1)
    for col, val in enumerate(CHECKLIST_HEADERS, 1):
        ws.cell(row=1, column=col, value=val)
    for r, row_data in enumerate(CHECKLIST_ROWS, 2):
        for c, val in enumerate(row_data, 1):
            ws.cell(row=r, column=c, value=val)

def write_validation(ws):
    ws.delete_rows(1, ws.max_row or 1)
    for col, val in enumerate(VALIDATION_HEADERS, 1):
        ws.cell(row=1, column=col, value=val)
    for r, row_data in enumerate(VALIDATION_ROWS, 2):
        for c, val in enumerate(row_data, 1):
            ws.cell(row=r, column=c, value=val)

def main():
    wb = openpyxl.load_workbook(PATH)
    ws_cl = wb['Задание 1 чек-лист']
    ws_val = wb['Задание 1 данные валидации']
    write_checklist(ws_cl)
    write_validation(ws_val)
    wb.save(PATH)
    print('OK: чек-лист и данные валидации записаны.')

